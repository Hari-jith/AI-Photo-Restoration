"""
setup_backup_colorizer.py

Sets up the BACKUP colorizer: Zhang, Isola & Efros, SIGGRAPH 2017
("Real-Time User-Guided Image Colorization with Learned Deep Priors").

    python scripts/setup_backup_colorizer.py                # code + weights
    python scripts/setup_backup_colorizer.py --force        # fetch both again
    python scripts/setup_backup_colorizer.py --skip-weights # code only (no 130 MB download)

What it does
  1. Code: copies the network definition (siggraph17.py, base_color.py) and the
     LICENSE from the authors' GitHub repository into src/vendor/siggraph17/,
     pinned to one commit and checked against SHA-256 checksums. The files are
     unmodified copies (their imports are already relative).
  2. Weights: downloads siggraph17-df00044c.pth (about 130 MB) from the S3
     bucket that the authors' own code uses, into models/colorizer_backup/.
     The file name ends in the first 8 characters of its SHA-256 hash
     ("df00044c"); the authors' loader checks exactly that, and so do we.

Why this replaced the earlier Caffe model: its download address on the
Berkeley server now answers "404 Not Found". The authors' current repository
provides PyTorch versions hosted on S3 instead.

Needs scripts/download_weights.py (Module 10 version) in the same folder: its
download function (progress, .part file, size check) is reused here.
Both parts use only the Python standard library.
"""

import hashlib
import sys
import urllib.error
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

TARGET_DIR = PROJECT_ROOT / "src" / "vendor" / "siggraph17"
COMMIT = "4f6009ed1495b1300231ebeb41cc4015557ddef7"
RAW_BASE = f"https://raw.githubusercontent.com/richzhang/colorization/{COMMIT}/"

# (path in the repo, local name, sha256)
CODE_FILES = [
    ("colorizers/siggraph17.py", "siggraph17.py",
     "c78e3f2af8dd13d5fb7a9c7fc95f580f728f86a183b5ad2e12f6a48b282511bd"),
    ("colorizers/base_color.py", "base_color.py",
     "81cea88bb484866478138440f08cc8d6c3e3731652fe57592900e418b278da1d"),
    ("LICENSE", "LICENSE",
     "0df922ed99775db79b6f3c40b9d1d0b4d95194dcead6a5cac6cff2cf4006fade"),
]

WEIGHTS_URL = "https://colorizers.s3.us-east-2.amazonaws.com/siggraph17-df00044c.pth"
WEIGHTS_NAME = "siggraph17-df00044c.pth"
WEIGHTS_HASH_PREFIX = "df00044c"           # from the file name (torch-hub convention)
WEIGHTS_EXPECTED_BYTES = 136_787_426       # Content-Length reported by the server
WEIGHTS_MIN_BYTES = 130_000_000

NOTICE_TEXT = f"""SIGGRAPH 2017 colorization network (vendored)

Source:  https://github.com/richzhang/colorization  (commit {COMMIT})
Files:   colorizers/siggraph17.py, colorizers/base_color.py, LICENSE
Licence: BSD 2-Clause (see the LICENSE file in this folder)
Authors: Richard Zhang, Phillip Isola, Alexei A. Efros
Paper:   "Real-Time User-Guided Image Colorization with Learned Deep Priors", SIGGRAPH 2017

Changes made by this project: none. The files are unmodified copies.
The trained weights are downloaded separately from the authors' S3 bucket
(see scripts/setup_backup_colorizer.py). They were trained on ImageNet.

This folder is generated by scripts/setup_backup_colorizer.py.
"""


def hash_prefix_matches(path: Path, prefix: str, file_hash=None) -> bool:
    """True if the file's SHA-256 starts with `prefix` (torch-hub style check)."""
    if file_hash is None:
        from download_weights import file_sha256
        file_hash = file_sha256
    return file_hash(path).startswith(prefix)


def install_code(force: bool) -> bool:
    names = [local for _, local, _ in CODE_FILES] + ["NOTICE.txt"]
    if not force and all((TARGET_DIR / n).is_file() for n in names):
        print(f"Code: already installed in {TARGET_DIR}")
        return True
    print(f"Code: fetching commit {COMMIT[:10]} ...")
    downloaded = {}
    for remote_path, local_name, expected in CODE_FILES:
        try:
            request = urllib.request.Request(
                RAW_BASE + remote_path, headers={"User-Agent": "photo-restorer-setup/1.0"})
            with urllib.request.urlopen(request, timeout=30) as response:
                data = response.read()
        except (urllib.error.URLError, TimeoutError, OSError) as error:
            print(f"  FAILED to download {remote_path}: {error}")
            return False
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            print(f"  CHECKSUM MISMATCH for {remote_path}\n    expected {expected}\n"
                  f"    got      {actual}\n  Nothing was installed.")
            return False
        downloaded[local_name] = data
        print(f"  ok  {local_name}")
    TARGET_DIR.mkdir(parents=True, exist_ok=True)
    for local_name, data in downloaded.items():
        (TARGET_DIR / local_name).write_bytes(data)
    (TARGET_DIR / "NOTICE.txt").write_text(NOTICE_TEXT, encoding="utf-8")
    print(f"  installed in {TARGET_DIR}")
    return True


def install_weights(force: bool) -> bool:
    try:
        from download_weights import download_one_url, file_sha256
        from src import config
    except ImportError as error:
        print("Weights: this script needs scripts/download_weights.py (the Module 10 "
              f"version) in the same folder. ({error})")
        return False

    destination = config.MODELS_DIR / "colorizer_backup" / WEIGHTS_NAME
    if destination.is_file() and not force:
        if (destination.stat().st_size >= WEIGHTS_MIN_BYTES
                and hash_prefix_matches(destination, WEIGHTS_HASH_PREFIX, file_sha256)):
            print(f"Weights: already present and verified ({destination.name})")
            return True
        print("Weights: the existing file looks wrong; downloading again.")

    print(f"Weights: downloading {WEIGHTS_NAME} (about 130 MB) ...")
    try:
        download_one_url(WEIGHTS_URL, destination, WEIGHTS_MIN_BYTES)
    except urllib.error.HTTPError as error:
        print(f"  FAILED: server answered {error.code} {error.reason}")
        return _manual_help(destination)
    except (urllib.error.URLError, TimeoutError) as error:
        print(f"  FAILED: could not connect ({error}). Check your internet connection or firewall.")
        return _manual_help(destination)
    except (OSError, ValueError) as error:
        print(f"  FAILED: {error}")
        return _manual_help(destination)

    full_hash = file_sha256(destination)
    if not full_hash.startswith(WEIGHTS_HASH_PREFIX):
        destination.unlink()
        print(f"  The downloaded file is NOT the expected one (its hash starts with "
              f"{full_hash[:8]}, expected {WEIGHTS_HASH_PREFIX}); it was deleted.")
        return False
    size = destination.stat().st_size if destination.exists() else 0
    note = "" if size == WEIGHTS_EXPECTED_BYTES else f" (size {size}, expected {WEIGHTS_EXPECTED_BYTES})"
    print(f"  saved and verified: {destination}{note}")
    print(f"  full SHA-256: {full_hash}")
    return True


def _manual_help(destination: Path) -> bool:
    print(f"  Manual download: open  {WEIGHTS_URL}\n  in a browser and save it as:\n"
          f"  {destination}")
    return False


def main() -> int:
    args = sys.argv[1:]
    force = "--force" in args
    ok = install_code(force)
    if "--skip-weights" not in args:
        ok = install_weights(force) and ok
    if ok:
        print("\nDone. The backup colorizer is ready.")
        return 0
    print("\nSomething needs attention (see above). Fix it and run this script again.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
